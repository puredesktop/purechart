// Requires the running desktop dev shell. Creates a uniquely named QA draft;
// does not delete files or modify pre-existing chart data. Reopens the starting document.
// QA_DRAFTS_DIR must be the desktop app's actual drafts directory.
import { chromium } from 'playwright'
import { readFile } from 'node:fs/promises'
import path from 'node:path'
import assert from 'node:assert/strict'
if (!process.env.QA_DRAFTS_DIR) throw new Error('Set QA_DRAFTS_DIR to the desktop drafts directory.')
const browser = await chromium.connectOverCDP(process.env.PURECHART_CDP ?? 'http://localhost:9336')
const page = browser.contexts()[0].pages().find(p => p.url().startsWith('http://localhost:5170'))
if (!page) throw new Error('Desktop dev shell is not running.')
const frame = () => page.frames().find(f => f.url().startsWith('http://localhost:5193'))
const title = `PureChart QA ${Date.now()}`
const chartPath = path.join(process.env.QA_DRAFTS_DIR, `${title}.chart`)
const csv = 'region,north,south\nA,10,15\nB,20,12\nC,30,24'
async function saved(f) { await f.waitForFunction(() => document.body.innerText.includes('Saved ·')) }
async function openPicker(f) {
  if (!await f.getByText('Open a chart', { exact: true }).isVisible()) await f.locator('button[title="Switch documents (⌘O)"]').click()
}
try {
  let f = frame()
  if (!f) throw new Error('Open PureChart before running this check.')
  const original = await f.locator('button[title="Switch documents (⌘O)"]').textContent()
  await openPicker(f)
  await f.getByRole('button', { name: 'New chart' }).click()
  await f.getByRole('textbox', { name: 'Document name', exact: true }).fill(title)
  await f.getByRole('textbox', { name: 'Document name', exact: true }).press('Tab')
  await f.getByRole('button', { name: 'Data', exact: true }).click()
  await f.locator('input[type=file]').setInputFiles({ name: 'qa.csv', mimeType: 'text/csv', buffer: Buffer.from(csv) })
  await f.getByRole('button', { name: 'Apply data', exact: true }).click()
  await f.getByRole('textbox', { name: 'Chart name', exact: true }).fill('QA north')
  await f.getByRole('textbox', { name: 'Chart name', exact: true }).press('Tab')
  await f.getByRole('button', { name: '‹ Sheet', exact: true }).click()
  await f.getByRole('button', { name: 'Duplicate', exact: true }).click()
  await f.getByRole('textbox', { name: 'Chart name', exact: true }).fill('QA comparison')
  await f.getByRole('textbox', { name: 'Chart name', exact: true }).press('Tab')
  await f.getByRole('button', { name: 'Chart', exact: true }).click()
  await f.getByRole('button', { name: 'Type', exact: true }).click()
  await f.getByText('Line', { exact: true }).click()
  await f.getByRole('button', { name: 'Add Y measure', exact: true }).click()
  await f.getByText('south', { exact: true }).first().click()
  await saved(f)
  assert.equal(await f.locator('button[title="Switch documents (⌘O)"]').textContent(), `${title}.chart`)
  const before = JSON.parse(await readFile(path.join(chartPath, 'chart.json'), 'utf8'))
  assert.equal(before.title, title)
  assert.equal(before.data.inline.text, csv)
  assert.deepEqual(before.charts.map(c => c.spec.title), ['QA north', 'QA comparison'])
  assert.deepEqual(before.charts[1].spec.chart.encodings.y, ['north', 'south'])
  await f.getByRole('button', { name: 'Export', exact: true }).click()
  await f.getByRole('button', { name: 'Export SVG', exact: true }).click()
  await f.getByRole('button', { name: 'Export PNG', exact: true }).click()
  await f.waitForFunction(() => document.body.innerText.includes('Exported qa-comparison.png'))
  const svg = await readFile(path.join(chartPath, 'assets/figures/qa-comparison.svg'), 'utf8')
  const png = await readFile(path.join(chartPath, 'assets/figures/qa-comparison.png'))
  assert.match(svg, /QA comparison/)
  assert.match(svg, /viewBox="0 0 1200 800"/)
  assert.equal(png.readUInt32BE(16), 1200)
  assert.equal(png.readUInt32BE(20), 800)
  await saved(f)
  await f.getByRole('button', { name: 'Close this app and go to the desk', exact: true }).click()
  await page.waitForFunction(() => !document.querySelector('iframe[src*="5193"]'))
  await page.getByRole('button', { name: 'All apps', exact: true }).click()
  await page.getByRole('button', { name: 'Chart', exact: true }).click()
  await page.waitForFunction(() => !!document.querySelector('iframe[src*="5193"]'))
  f = frame()
  await openPicker(f)
  await f.getByText(title, { exact: true }).first().click()
  await f.getByRole('button', { name: 'Open QA comparison', exact: true }).waitFor()
  await saved(f)
  assert.equal(await f.getByRole('textbox', { name: 'Document name', exact: true }).inputValue(), title)
  await f.getByRole('button', { name: 'Open QA comparison', exact: true }).click()
  await f.getByRole('button', { name: 'Chart', exact: true }).click()
  assert.equal(await f.getByRole('button', { name: 'Type', exact: true }).textContent(), 'Line')
  assert.match(await f.getByLabel('Selected Y measures').innerText(), /north[\s\S]*south/)
  await page.screenshot({ path: '/tmp/purechart-desktop-reopened.png' })
  const after = JSON.parse(await readFile(path.join(chartPath, 'chart.json'), 'utf8'))
  assert.deepEqual(after, before)
  await openPicker(f)
  await f.getByText(original.replace(/\.chart$/, ''), { exact: true }).first().click()
  console.log(JSON.stringify({ result: 'Desktop import, multiple charts, edit, save, SVG/PNG export, close and reopen passed.', chartPath }))
} finally { await browser.close() }
